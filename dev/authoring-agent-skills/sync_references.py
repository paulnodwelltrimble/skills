#!/usr/bin/env python3
"""Split the best-practices page into the phase reference files.

The page is the single source of truth; never hand-edit references/*.md.

Usage: python3 dev/authoring-agent-skills/sync_references.py <best-practices.md> [--check]
  --check  exit 1 if references/ is out of date (for CI), write nothing.
Exit codes: 0 ok, 1 out of date (--check), 2 bad input.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# Section number (or heading title) -> reference file.
PHASES: dict[str, list[str]] = {
    "decide.md": ["1", "2", "4", "16"],
    "authoring.md": ["3", "5", "11", "12", "15", "18", "Reference layout"],
    "evals.md": ["8"],
    "runtime.md": ["6", "7", "9"],
    "ship.md": ["10", "13", "14", "17", "19", "20"],
    "sources.md": ["Disagreements", "Unverified", "Key sources"],
}
HEADER = "<!-- Generated by scripts/sync_references.py from the best-practices page. Do not edit. -->\n\n"


def split_sections(text: str) -> dict[str, str]:
    sections: dict[str, str] = {}
    for chunk in re.split(r"(?m)^(?=## )", text):
        m = re.match(r"## (?:(\d+)\.|([^\n]+))", chunk)
        if m:
            sections[m.group(1) or m.group(2).strip()] = chunk.rstrip() + "\n"
    return sections


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("page", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if not args.page.is_file():
        print(f"page not found: {args.page}", file=sys.stderr)
        return 2
    sections = split_sections(args.page.read_text(encoding="utf-8"))
    missing = [k for keys in PHASES.values() for k in keys if k not in sections]
    if missing:
        print(f"page is missing sections {missing}; update PHASES in {__file__}", file=sys.stderr)
        return 2
    out_dir = Path(__file__).resolve().parents[2] / "skills" / "authoring-agent-skills" / "references"
    stale = []
    for name, keys in PHASES.items():
        body = HEADER + "\n".join(sections[k] for k in keys)
        path = out_dir / name
        if not path.is_file() or path.read_text(encoding="utf-8") != body:
            stale.append(name)
            if not args.check:
                out_dir.mkdir(exist_ok=True)
                path.write_text(body, encoding="utf-8")
    print(json.dumps({"stale" if args.check else "written": stale}))
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
